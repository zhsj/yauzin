package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"strings"
)

// initialisms are the words the Gmail API spells in capitals. The list is what
// keeps the generated fields named like the hand-written ones they replace
// (ID, IDs, MIMEType, AttachmentID), so call sites only change type names.
var initialisms = map[string]string{
	"api":    "API",
	"cc":     "CC",
	"cn":     "CN",
	"cse":    "CSE",
	"html":   "HTML",
	"id":     "ID",
	"ids":    "IDs",
	"imap":   "IMAP",
	"kacls":  "KACLS",
	"mime":   "MIME",
	"pem":    "PEM",
	"pkcs7":  "PKCS7",
	"pkcs12": "PKCS12",
	"pop":    "POP",
	"smime":  "SMIME",
	"smtp":   "SMTP",
	"uri":    "URI",
	"url":    "URL",
}

// generate turns a Discovery document into the Go source of its schema types.
func generate(raw []byte, pkg string) ([]byte, error) {
	var s spec
	if err := json.Unmarshal(raw, &s); err != nil {
		return nil, fmt.Errorf("parse discovery document: %w", err)
	}
	if len(s.Schemas) == 0 {
		return nil, fmt.Errorf("discovery document has no schemas")
	}

	var body strings.Builder
	var degraded []string
	needsJSON := false
	for _, name := range sortedKeys(s.Schemas) {
		decl, deg, err := renderStruct(name, s.Schemas[name])
		if err != nil {
			return nil, err
		}
		body.WriteString(decl)
		body.WriteString("\n")
		degraded = append(degraded, deg...)
	}
	needsJSON = len(degraded) > 0

	var src strings.Builder
	src.WriteString("// Code generated by gmailgen. DO NOT EDIT.\n//\n")
	fmt.Fprintf(&src, "// Source:   %s\n", discoveryURL)
	fmt.Fprintf(&src, "// Revision: %s\n", s.Revision)
	if len(degraded) > 0 {
		src.WriteString("//\n// Degraded to json.RawMessage:\n")
		for _, field := range degraded {
			fmt.Fprintf(&src, "//   %s\n", field)
		}
	}
	fmt.Fprintf(&src, "\npackage %s\n\n", pkg)
	if needsJSON {
		src.WriteString("import \"encoding/json\"\n\n")
	}
	src.WriteString(body.String())

	out, err := format.Source([]byte(src.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return out, nil
}

// renderStruct renders one schema as a struct declaration.
func renderStruct(schemaName string, s schema) (string, []string, error) {
	name := typeName(schemaName)
	var b strings.Builder
	fmt.Fprintf(&b, "// %s mirrors the %q schema of the Gmail API.\n", name, schemaName)
	fmt.Fprintf(&b, "type %s struct {\n", name)

	seen := make(map[string]string, len(s.Properties))
	var degraded []string
	for _, jsonName := range sortedKeys(s.Properties) {
		field := exportName(jsonName)
		if prev, ok := seen[field]; ok {
			return "", nil, fmt.Errorf("%s: fields %q and %q both map to %s", schemaName, prev, jsonName, field)
		}
		seen[field] = jsonName

		typ, degradedType := goType(s.Properties[jsonName])
		if degradedType {
			degraded = append(degraded, schemaName+"."+jsonName)
		}
		fmt.Fprintf(&b, "%s %s `json:\"%s\"`\n", field, typ, jsonName)
	}
	b.WriteString("}\n")
	return b.String(), degraded, nil
}

// typeName converts a schema name to a Go identifier.
func typeName(name string) string { return exportName(name) }

// exportName converts a JSON name to an exported Go identifier.
func exportName(in string) string {
	words := splitWords(in)
	for i, word := range words {
		if v, ok := initialisms[strings.ToLower(word)]; ok {
			words[i] = v
			continue
		}
		runes := []rune(word)
		words[i] = strings.ToUpper(string(runes[0])) + string(runes[1:])
	}
	return strings.Join(words, "")
}

// splitWords cuts a camelCase or PascalCase name into words. Digits stay with
// the word they follow, so "pkcs12" remains one word for the initialism table.
func splitWords(in string) []string {
	runes := []rune(in)
	var words []string
	start := 0
	for i := 1; i < len(runes); i++ {
		prev, cur := runes[i-1], runes[i]
		if isUpper(cur) && (isLower(prev) || isDigit(prev)) {
			words = append(words, string(runes[start:i]))
			start = i
			continue
		}
		// End of an acronym that starts a new word: "IDCard" is "ID" + "Card".
		if isUpper(prev) && isUpper(cur) && i+1 < len(runes) && isLower(runes[i+1]) {
			words = append(words, string(runes[start:i]))
			start = i
		}
	}
	return append(words, string(runes[start:]))
}

func isUpper(r rune) bool { return r >= 'A' && r <= 'Z' }

func isLower(r rune) bool { return r >= 'a' && r <= 'z' }

func isDigit(r rune) bool { return r >= '0' && r <= '9' }
