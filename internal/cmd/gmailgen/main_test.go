package main

import (
	"bytes"
	"flag"
	"os"
	"strings"
	"testing"
)

var update = flag.Bool("update", false, "rewrite the golden file")

func TestGenerateMatchesGolden(t *testing.T) {
	raw, err := os.ReadFile("testdata/spec.json")
	if err != nil {
		t.Fatalf("read fixture: %v", err)
	}
	got, err := generate(raw, "gmail")
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	const golden = "testdata/spec.golden"
	if *update {
		if err := os.WriteFile(golden, got, 0o644); err != nil {
			t.Fatalf("write golden: %v", err)
		}
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatalf("read golden: %v", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("generated source differs from %s:\n--- got ---\n%s", golden, got)
	}
}

func TestGenerateIsDeterministic(t *testing.T) {
	raw, err := os.ReadFile("testdata/spec.json")
	if err != nil {
		t.Fatalf("read fixture: %v", err)
	}
	first, err := generate(raw, "gmail")
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	for i := 0; i < 3; i++ {
		again, err := generate(raw, "gmail")
		if err != nil {
			t.Fatalf("generate: %v", err)
		}
		if !bytes.Equal(first, again) {
			t.Fatal("two runs produced different output")
		}
	}
}

func TestGenerateRecordsRevisionAndDegradations(t *testing.T) {
	raw, err := os.ReadFile("testdata/spec.json")
	if err != nil {
		t.Fatalf("read fixture: %v", err)
	}
	src, err := generate(raw, "gmail")
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	got := string(src)
	for _, want := range []string{
		"// Code generated by gmailgen. DO NOT EDIT.",
		"// Revision: test-1",
		"//   Alpha.odd",
		"json.RawMessage",
		"`json:\"odd\"`",
		"import \"encoding/json\"",
	} {
		if !strings.Contains(got, want) {
			t.Fatalf("generated source lacks %q:\n%s", want, got)
		}
	}
}

func TestGenerateRejectsDocumentWithoutSchemas(t *testing.T) {
	if _, err := generate([]byte(`{"revision":"x"}`), "gmail"); err == nil {
		t.Fatal("a document without schemas was accepted")
	}
	if _, err := generate([]byte(`not json`), "gmail"); err == nil {
		t.Fatal("malformed JSON was accepted")
	}
}

func TestExportName(t *testing.T) {
	cases := map[string]string{
		"id":                        "ID",
		"ids":                       "IDs",
		"labelIds":                  "LabelIDs",
		"mimeType":                  "MIMEType",
		"internalDate":              "InternalDate",
		"attachmentId":              "AttachmentID",
		"backgroundColor":           "BackgroundColor",
		"cseIdentities":             "CSEIdentities",
		"signAndEncryptKeyPairs":    "SignAndEncryptKeyPairs",
		"smtpMsa":                   "SMTPMsa",
		"issuerCn":                  "IssuerCN",
		"pkcs12":                    "PKCS12",
		"kaclsUri":                  "KACLSURI",
		"ListCseIdentitiesResponse": "ListCSEIdentitiesResponse",
	}
	for in, want := range cases {
		if got := exportName(in); got != want {
			t.Errorf("exportName(%q) = %q, want %q", in, got, want)
		}
	}
}
